const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('../frontend/node_modules/@playwright/test')

async function main() {
  const url = process.env.APP_URL || 'http://127.0.0.1:5173'
  const output = process.env.BROWSER_OUTPUT_DIR || 'test-results/roundtable'
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH, headless: true })
  const context = await browser.newContext({ viewport: { width: 1672, height: 941 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  try {
    await page.goto(url + '/review')
    const startFromSidebar = page.getByRole('navigation', { name: '主导航' })
      .getByRole('button', { name: '圆桌讨论', exact: true })
    await startFromSidebar.click()
    const standalone = page.getByRole('dialog', { name: '圆桌讨论', exact: true })
    const standaloneTopic = standalone.getByLabel('讨论议题', { exact: true })
    const participantCount = standalone.getByLabel('讨论者人数', { exact: true })
    const startStandalone = standalone.getByRole('button', { name: '启动圆桌讨论', exact: true })
    assert.equal(await standaloneTopic.inputValue(), '')
    assert.equal(await participantCount.inputValue(), '')
    await standaloneTopic.fill('怎样比较这两种水杯广告策略？')
    assert.equal(await startStandalone.isEnabled(), false)
    await participantCount.fill('4')
    fs.mkdirSync(output, { recursive: true })
    await page.screenshot({ path: path.join(output, 'standalone-setup.png') })
    await startStandalone.click()
    await standalone.locator('[data-meeting-status="finished"]').waitFor()
    assert.equal(await standalone.locator('[data-seat-id]').count(), 5)
    assert.equal(await standalone.getByText('本次审核依据', { exact: true }).count(), 0)
    await standalone.getByRole('button', { name: '返回工作区', exact: true }).click()
    await startFromSidebar.click()
    await standalone.locator('[data-meeting-status="finished"]').waitFor()
    assert.equal(await standalone.locator('[data-seat-id]').count(), 5)
    await standalone.getByRole('button', { name: '返回工作区', exact: true }).click()

    await page.getByRole('button', { name: '打开预设案例' }).click()
    await page.getByRole('button', { name: '圆桌复核', exact: true }).first().click()
    const dialog = page.getByRole('dialog', { name: '圆桌复核' })
    assert.match(await dialog.getByLabel('你想核对的问题').inputValue(), /100% Eco-Friendly/)
    await dialog.getByLabel('你想核对的问题').fill('现有证据能否支持 100% Eco-Friendly 宣称？')
    let allowStart
    const release = new Promise((resolve) => { allowStart = resolve })
    await page.route('**/api/reviews/*/risks/*/discussions', async (route) => {
      await release
      await route.continue()
    })
    try {
      await dialog.getByRole('button', { name: '启动圆桌讨论' }).click()
      await dialog.getByText('正在组建圆桌').waitFor()
      assert.equal(await dialog.getByRole('button', { name: '返回审核' }).isEnabled(), false)
      await page.keyboard.press('Escape')
      assert.equal(await dialog.isVisible(), true)
    } finally {
      allowStart()
    }
    await dialog.locator('[data-meeting-status="finished"]').waitFor()
    await dialog.getByRole('img', { name: '木质圆桌' }).waitFor()
    assert.equal(await dialog.locator('[data-seat-id]').count(), 4)
    assert.equal(await dialog.locator('.rt-round-heading').count(), 3)
    const firstRound = dialog.getByRole('button', { name: '第 1 轮 · 初步解读' })
    if (await firstRound.getAttribute('aria-expanded') === 'false') await firstRound.click()
    await dialog.locator('[data-turn-index="2"]').click()
    const bubble = dialog.locator('[data-speaking-for]')
    assert.equal(await bubble.count(), 1)
    const speakerId = await bubble.getAttribute('data-speaking-for')
    assert.equal(await dialog.locator('[data-spotlight-for]').getAttribute('data-spotlight-for'), speakerId)
    const light = await dialog.locator('[data-spotlight-for]').boundingBox()
    const speakerSeat = await dialog.locator(`[data-seat-id="${speakerId}"]`).boundingBox()
    assert.ok(Math.abs((light.x + light.width / 2) - (speakerSeat.x + speakerSeat.width / 2)) < 2)

    const other = dialog.locator(`[data-seat-id]:not([data-seat-id="${speakerId}"])`).first()
    const beforeHover = await other.boundingBox()
    await other.hover()
    await dialog.locator('.rt-persona').waitFor()
    assert.deepEqual(await other.boundingBox(), beforeHover, 'hover must not move the seat')
    assert.equal(await bubble.getAttribute('data-speaking-for'), speakerId)
    fs.mkdirSync(output, { recursive: true })
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.rt-light')).opacity) >= 0.99)
    await page.screenshot({ path: path.join(output, 'roundtable-desktop.png') })
    const portraits = dialog.locator('[data-seat-id] [data-portrait-index]')
    assert.equal(await portraits.count(), 4)
    assert.ok(await (await page.request.get(url + '/roundtable/portraits.png')).ok())
    assert.ok(await portraits.evaluateAll((entries) => entries.every(
      (entry) => getComputedStyle(entry).backgroundImage.includes('/roundtable/portraits.png'),
    )))

    await other.click()
    assert.equal(await dialog.locator('.rt-persona [data-portrait-index]').getAttribute('data-portrait-index'),
      await other.locator('[data-portrait-index]').getAttribute('data-portrait-index'))
    await dialog.getByRole('button', { name: '关闭人设' }).click()

    await page.mouse.move(10, 10)
    await dialog.getByRole('button', { name: '下一条发言' }).click()
    assert.equal(await bubble.count(), 1)
    assert.notEqual(await bubble.getAttribute('data-speaking-for'), speakerId)
    await dialog.getByText('主持纪要', { exact: true }).click()
    await dialog.getByText('演示纪要', { exact: false }).last().waitFor()
    await page.setViewportSize({ width: 1040, height: 460 })
    const landscapeBubble = await bubble.boundingBox()
    const landscapeStage = await dialog.locator('.rt-stage').boundingBox()
    assert.ok(landscapeBubble.y >= landscapeStage.y, 'speech should fit above the portrait in short viewports')
    await page.setViewportSize({ width: 390, height: 844 })
    const controls = dialog.locator('.rt-controls')
    const mobileControls = await controls.boundingBox()
    assert.ok(mobileControls.y + mobileControls.height <= 844)
    await dialog.locator('.rt-main').evaluate((main) => { main.scrollTop = 0 })
    assert.equal(await dialog.evaluate((el) => el.scrollWidth > el.clientWidth), false)
    const mobileBubble = await bubble.boundingBox()
    assert.ok(mobileBubble.x >= 0 && mobileBubble.x + mobileBubble.width <= 390)

    await page.screenshot({ path: path.join(output, 'roundtable-mobile.png') })
    await dialog.getByRole('button', { name: '返回审核' }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('heading', { name: '每项风险，都能追溯。' }).waitFor()
    await page.getByRole('button', { name: '圆桌复核', exact: true }).first().click()
    await dialog.locator('[data-meeting-status="finished"]').waitFor()
    assert.equal(await dialog.locator('[data-seat-id]').count(), 4)

    const jury = await context.newPage()
    jury.on('pageerror', (error) => errors.push(error.message))
    await jury.goto(url + '/jury')
    await jury.getByRole('button', { name: '用水杯样例', exact: true }).click()
    await jury.getByRole('spinbutton', { name: '测试人像数' }).fill('2')
    const savedPanel = jury.waitForResponse((response) => (
      response.url().endsWith('/api/jury/panels') && response.request().method() === 'POST'
    ))
    await jury.getByRole('button', { name: '生成人像', exact: true }).click()
    const panel = await (await savedPanel).json()
    await jury.getByText('数字人像已保存，可以填写两版文案。', { exact: true }).waitFor()
    await jury.close()

    await page.setViewportSize({ width: 1672, height: 941 })
    await dialog.getByRole('button', { name: '发起新讨论' }).click()
    const member = panel.members[1]
    const chooser = dialog.getByLabel('邀请数字人像（可选）')
    await chooser.selectOption(panel.panel_id + ':' + member.member_id)
    assert.equal(await chooser.locator('option:checked').textContent(), member.specification.persona.name)
    await page.screenshot({ path: path.join(output, 'invite-picker.png') })
    const created = page.waitForResponse((response) => response.url().endsWith('/discussions'))
    await dialog.getByRole('button', { name: '启动圆桌讨论' }).click()
    const meeting = await (await created).json()
    await dialog.locator('[data-meeting-status="finished"]').waitFor()
    const saved = await (await page.request.get(url + '/api/discussions/' + meeting.discussion_id)).json()
    const guest = saved.participants.find((participant) => participant.id === member.member_id)
    assert.equal(guest.name, member.specification.persona.name)
    assert.equal(await portraits.count(), 5)
    assert.equal(new Set(Object.values(saved.avatar_indices)).size, 5)
    const guestSeat = dialog.locator(`[data-seat-id="${guest.id}"][data-invited="true"]`)
    await guestSeat.getByText('受邀数字人像').waitFor()
    assert.equal(Number(await guestSeat.locator('[data-portrait-index]').getAttribute('data-portrait-index')),
      saved.avatar_indices[guest.id])
    const guestTurn = saved.turns.findIndex((value) => value.speaker_id === guest.id)
    assert.ok(guestTurn > 0, 'the selected persona has a real discussion turn')
    if (await firstRound.getAttribute('aria-expanded') === 'false') await firstRound.click()
    await dialog.locator(`[data-turn-index="${guestTurn}"]`).click()
    assert.equal(await bubble.getAttribute('data-speaking-for'), guest.id)
    assert.equal(await dialog.locator('[data-spotlight-for]').getAttribute('data-spotlight-for'), guest.id)
    await guestSeat.hover()
    await dialog.getByRole('complementary', { name: guest.name + ' 的人设' }).waitFor()
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.rt-light')).opacity) >= 0.99)
    await page.screenshot({ path: path.join(output, 'roundtable-invited.png') })

    await page.setViewportSize({ width: 650, height: 840 })
    const plates = await dialog.locator('.rt-nameplate').evaluateAll((labels) =>
      labels.map((label) => label.getBoundingClientRect().toJSON()))
    assert.ok(plates.every((plate, index) => !index || plates[index - 1].right <= plate.left + 1))

    await page.setViewportSize({ width: 390, height: 844 })
    await dialog.locator('.rt-main').evaluate((main) => { main.scrollTop = 0 })
    const seats = await dialog.locator('[data-seat-id]').evaluateAll((buttons) =>
      buttons.map((button) => button.getBoundingClientRect().toJSON()))
    assert.ok(seats.every((seat, index) => !index || seats[index - 1].right <= seat.left + 1))
    assert.equal(await dialog.evaluate((el) => el.scrollWidth > el.clientWidth), false)
    await page.screenshot({ path: path.join(output, 'roundtable-invited-mobile.png') })
    await dialog.getByRole('button', { name: '返回审核' }).click()
    await page.getByRole('button', { name: '圆桌复核', exact: true }).first().click()
    await guestSeat.waitFor()
    assert.equal(await dialog.locator('[data-seat-id]').count(), 5)
    assert.deepEqual(errors, [])
    console.log('Passed: standalone topic and seat count, risk-specific prefilled topic, saved guest, stable seats, spotlight, rounds, mobile and reopen.')
  } finally {
    await browser.close()
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
