const { chromium } = require('../frontend/node_modules/@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
async function main() {
  const output = path.resolve('test-results/materials-browser')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1703, height: 955 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const backend = process.env.API_PROXY_URL || 'http://127.0.0.1:8013'
  const campaignName = `联合审核验证 ${Date.now()}`
  try {
    await page.goto(`${process.env.APP_URL || 'http://127.0.0.1:5177'}/?ui=v2`)
    await page.locator('.example-card').nth(3).waitFor()
    if (await page.locator('.example-card.negative').count() !== 3 || await page.locator('.example-card.positive').count() !== 1) throw new Error('Expected 3 negative, 1 positive in the same library')
    if (await page.locator('.setup-grid .example-card, .setup-grid .demo-card').count()) throw new Error('Example is still beside the form')
    if (await page.getByLabel('目标市场', { exact: true }).locator('option').count() !== 9) throw new Error('Market options missing')
    if (await page.getByLabel('商品类别', { exact: true }).locator('option').count() !== 10) throw new Error('Category options missing')
    await page.screenshot({ path: path.join(output, 'setup-1703.png'), fullPage: true })
    await page.getByLabel('项目名称', { exact: true }).fill(campaignName)
    await page.getByLabel('商品类别', { exact: true }).selectOption('electronics')
    await page.getByRole('radio', { name: '图片＋文案', exact: true }).check()
    const submit = page.getByRole('button', { name: '提交并开始审核' })
    if (await submit.isEnabled()) throw new Error('Empty combined input can submit')
    await page.getByRole('textbox', { name: '广告文案', exact: true }).fill('100% Eco-Friendly. Additional description.')
    if (await submit.isEnabled()) throw new Error('Combined input missing image can submit')
    await page.getByLabel('选择广告图片').setInputFiles('examples/eco-bottle.png')
    await submit.click()
    await page.locator('.risk-card').waitFor()
    await page.getByRole('heading', { name: '同时提交的广告文案' }).waitFor()
    await page.locator('.attached-copy .text-risk').click()
    if (await page.locator('.risk-card.active').count() !== 1) throw new Error('Supplied copy risk does not select')
    if (!(await page.locator('.intro').first().innerText()).includes('电子数码与家电')) throw new Error('Product context lost')
    await page.screenshot({ path: path.join(output, 'combined-review.png'), fullPage: true })
    await page.reload()
    await page.getByRole('heading', { name: '同时提交的广告文案' }).waitFor()
    await page.getByRole('button', { name: '项目与素材', exact: true }).click()
    const choice = page.getByLabel('所属项目', { exact: true })
    await choice.selectOption({ label: campaignName })
    await page.getByRole('radio', { name: '广告文案', exact: true }).check()
    if (await page.getByLabel('选择广告图片').count()) throw new Error('Text-only still requires image')
    await page.getByRole('textbox', { name: '广告文案', exact: true }).fill('100% Eco-Friendly. Text-only campaign.')
    await page.getByRole('button', { name: '提交并开始审核' }).click()
    await page.getByRole('heading', { name: '广告文案', exact: true }).waitFor()
    await page.locator('.risk-card').waitFor()
    if (await page.locator('.asset-canvas img').count()) throw new Error('Text-only shows image')
    const projects = await (await page.request.get(`${backend}/api/projects`)).json()
    const same = projects.filter(p => p.name === campaignName)
    if (same.length !== 1) throw new Error('Reusing project created a duplicate')
    const history = await (await page.request.get(`${backend}/api/projects/${same[0].project_id}/reviews`)).json()
    if (history.length !== 2) throw new Error('Both input types not saved under same project')
    await page.getByRole('button', { name: '项目与素材', exact: true }).click()
    await page.getByLabel('目标市场', { exact: true }).selectOption('US')
    await page.getByLabel('商品类别', { exact: true }).selectOption('beauty')
    await page.getByLabel('项目名称', { exact: true }).fill('美国美妆素材')
    await page.getByRole('radio', { name: '广告文案', exact: true }).check()
    await page.getByRole('textbox', { name: '广告文案', exact: true }).fill('100% Eco-Friendly. Product description.')
    await page.getByRole('button', { name: '保存并提取宣称' }).click()
    await page.getByRole('heading', { name: '等待接入该市场规则' }).waitFor()
    if (!(await page.locator('.intro').first().innerText()).includes('美国')) throw new Error('US input mislabeled')
    if (await page.locator('.risk-card').count()) throw new Error('Uncovered market received a verdict')
    await page.getByRole('heading', { name: '提取的宣称' }).waitFor()
    for (const width of [320, 390, 740, 890, 1440]) {
      await page.setViewportSize({ width, height: 955 })
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`Unsupported market view overflows at ${width}`)
    }
    await page.getByRole('button', { name: '项目与素材', exact: true }).click()
    for (const width of [320, 390, 740, 890, 1440]) {
      await page.setViewportSize({ width, height: 955 })
      await page.getByRole('radio', { name: '图片＋文案', exact: true }).check()
      await page.getByRole('textbox', { name: '广告文案', exact: true }).fill('Combined submission layout check')
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`Combined setup overflows at ${width}`)
      if (width === 390 || width === 1440) await page.screenshot({ path: path.join(output, `combined-setup-${width}.png`), fullPage: true })
    }
    if (errors.length) throw new Error(errors.join('\n'))
    console.log('Material browser passed: unified 4 cases, 9 markets, 10 categories, combined submission, original image and copy, risk selection, reload, text-only in same project, uncovered market labels, mobile layouts.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })

