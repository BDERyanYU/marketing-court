const { chromium } = require('../frontend/node_modules/@playwright/test')
const path = require('node:path')
const fs = require('node:fs')
async function main() {
  const app = process.env.APP_URL || 'http://127.0.0.1:5177'
  const out = path.resolve('test-results/v3-materials-browser')
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1703, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto(app)
    await page.getByRole('button', { name: '＋ 创建项目', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('项目名称', { exact: true }).fill(`多素材项目 ${Date.now()}`)
    await dialog.getByRole('combobox').nth(2).selectOption('website')
    await dialog.getByRole('button', { name: '保存草稿', exact: true }).click()
    await page.getByRole('heading', { name: '还没有审核报告', exact: true }).waitFor()
    if (await page.getByRole('button', { name: '满意并归档', exact: true }).isEnabled()) throw Error('Draft can be archived as reviewed')
    await page.getByRole('button', { name: '添加版本', exact: true }).click()
    await dialog.getByRole('radio', { name: '图片＋文案', exact: true }).check()
    await dialog.getByLabel('选择广告图片', { exact: true }).setInputFiles('examples/eco-bottle.png')
    await dialog.getByRole('textbox', { name: '广告文案', exact: true }).fill('100% Eco-Friendly. Additional description.')
    await dialog.getByRole('button', { name: '保存并开始审核', exact: true }).click()
    await page.locator('.issue').waitFor()
    await page.getByRole('heading', { name: '同时提交的文案', exact: true }).waitFor()
    if (await page.locator('.asset-canvas img').count() !== 1) throw Error('Combined review missing image')
    await page.locator('.submitted-copy .text-risk').click()
    if (await page.locator('.issue.selected').count() !== 1) throw Error('Copy highlight did not select report issue')
    await page.getByRole('button', { name: '从当前素材派生画像', exact: true }).click()
    await dialog.getByRole('button', { name: '保存画像新版本', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByLabel('项目用户画像', { exact: true }).selectOption({ index: 0 })
    await page.getByRole('button', { name: '保存上下文', exact: true }).click()
    await page.getByText('项目上下文已保存，将用于下一轮审核。', { exact: true }).waitFor()
    await page.getByRole('button', { name: '添加版本', exact: true }).click()
    await dialog.getByRole('radio', { name: '广告文案', exact: true }).check()
    await dialog.getByRole('textbox', { name: '广告文案', exact: true }).fill('100% Eco-Friendly. New campaign text.')
    await dialog.getByRole('button', { name: '保存并开始审核', exact: true }).click()
    await page.getByText('素材与画像匹配意见', { exact: true }).waitFor()
    if (await page.locator('.asset-canvas img').count()) throw Error('Text-only review includes an image')
    await page.getByRole('radio', { name: '有争议', exact: true }).check()
    await page.getByRole('button', { name: '发起圆桌会议', exact: true }).first().click()
    for (const label of ['品牌方', '创意策划']) await dialog.getByRole('checkbox', { name: new RegExp(label) }).uncheck()
    await dialog.getByRole('button', { name: '进入圆桌工作区', exact: true }).click()
    for (let i=0;i<5;i++) {
      await page.getByRole('button', { name: /^推进：/ }).click()
      if (i<4) await page.locator('.meeting-turn').nth(i).waitFor()
      else await page.getByRole('button', { name: '回写审核报告', exact: true }).waitFor()
    }
    await page.getByRole('button', { name: '发起复审', exact: true }).click()
    await page.getByLabel('修改后文案', { exact: true }).fill('Meet the Everyday Bottle.')
    await page.getByRole('button', { name: '提交修改稿复审', exact: true }).click()
    await page.getByRole('heading', { name: '未识别到本主题待核查项', exact: true }).waitFor()
    await page.getByRole('radio', { name: '有争议', exact: true }).check()
    await page.getByRole('button', { name: '发起圆桌会议', exact: true }).first().waitFor()
    const report = await (await page.request.get(`${app}/api/workspace/projects`)).json()
    const p = report.find(v => v.project.channel === 'website')
    const detail = await (await page.request.get(`${app}/api/workspace/projects/${p.project.project_id}`)).json()
    if (detail.reviews.length !== 3 || !detail.assets.some(a => a.origin_meeting_id)) throw Error('Roundtable recheck lost project/version association')
    await page.getByLabel('审核版本', { exact: true }).selectOption({ index: 2 })
    await page.getByRole('heading', { name: '同时提交的文案', exact: true }).waitFor()
    await page.getByLabel('审核版本', { exact: true }).selectOption({ index: 0 })
    await page.getByRole('button', { name: '满意并归档', exact: true }).click()
    await page.getByRole('button', { name: '重新打开项目', exact: true }).waitFor()
    await page.screenshot({ path: path.join(out, 'contextual-project.png'), fullPage: true })
    await page.reload()
    await page.getByRole('button', { name: '重新打开项目', exact: true }).waitFor()
    if (errors.length) throw Error(errors.join('\n'))
    console.log('Workspace materials browser passed: draft, image+copy, image/copy risk selection, persona derivation/version/context, text-only contextual review, roundtable, new-version recheck, report-scope discussion, version switching and archive restore.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })

