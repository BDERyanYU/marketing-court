const { chromium } = require('../frontend/node_modules/@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
async function main() {
  const app = process.env.APP_URL || 'http://127.0.0.1:5176'
  const output = path.resolve('test-results/v3-browser')
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1703, height: 1000 }, reducedMotion: 'reduce' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  async function layout(name) { for (const width of [320, 390, 740, 890, 1440, 1703]) { await page.setViewportSize({ width, height: 1000 }); await page.locator('body').click({position:{x:1,y:1}}); await page.evaluate(() => window.scrollTo(0,0)); if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error(`${name} overflows at ${width}`); if ([390, 1703].includes(width)) await page.screenshot({ path: path.join(output, `${name}-${width}.png`), fullPage: true }) } }
  try {
    await page.goto(app)
    await page.getByRole('heading', { name: '从素材出发，让讨论形成下一步。' }).waitFor()
    await page.locator('.example-card').nth(3).waitFor()
    await layout('projects')
    await page.getByRole('button', { name: '用户画像', exact: true }).click()
    await page.getByRole('button', { name: '创建画像', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('画像名称', { exact: true }).fill(`环保消费者 ${Date.now()}`)
    await dialog.getByLabel('画像摘要', { exact: true }).fill('需要清楚了解材料范围和环保承诺，尚未经过真实调研验证。')
    await dialog.getByLabel('需求（每行一条，最多 8 条）', { exact: true }).fill('可核查的证据\n明确的材料范围')
    await dialog.getByRole('button', { name: '保存画像', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '出海营销项目', exact: true }).click()
    await page.getByRole('button', { name: '打开水杯「100% 环保」宣称', exact: true }).click()
    await page.getByRole('heading', { name: '审核报告', exact: true }).waitFor()
    await page.getByLabel('项目用户画像', { exact: true }).selectOption({ index: 0 })
    await page.getByRole('button', { name: '保存上下文', exact: true }).click()
    await page.getByText('项目上下文已保存，将用于下一轮审核。', { exact: true }).waitFor()
    await layout('project-detail')
    await page.getByRole('radio', { name: '有争议', exact: true }).check()
    await page.getByLabel('引用到圆桌', { exact: true }).check()
    await page.getByRole('button', { name: '发起圆桌会议', exact: true }).first().click()
    await dialog.waitFor()
    await dialog.getByLabel('会议议题', { exact: true }).fill('环保承诺如何修改才更清晰')
    for (const label of ['品牌方', '创意策划']) await dialog.getByRole('checkbox', { name: new RegExp(label) }).uncheck()
    await page.screenshot({ path: path.join(output, 'meeting-dialog.png'), fullPage: true })
    await dialog.getByRole('button', { name: '进入圆桌工作区' }).click()
    await page.getByRole('heading', { name: '环保承诺如何修改才更清晰', exact: true }).waitFor()
    await layout('meeting-empty')
    await page.getByLabel('补充指令（可选）', { exact: true }).fill('重点说明证据范围与消费者理解')
    await page.getByRole('button', { name: '推进：目标消费者代表', exact: true }).click()
    await page.locator('.meeting-turn').first().waitFor()
    await page.reload()
    await page.locator('.meeting-turn').first().waitFor()
    for (let i = 1; i < 5; i++) {
      await page.getByRole('button', { name: /^推进：/ }).click()
      if (i < 4) await page.locator('.meeting-turn').nth(i).waitFor()
      else await page.getByRole('button', { name: '回写审核报告', exact: true }).waitFor()
    }
    if (await page.locator('.meeting-turn').count() !== 4) throw Error('Wrong turn count')
    await layout('meeting-complete')
    await page.getByRole('button', { name: '回写审核报告', exact: true }).click()
    await page.getByRole('button', { name: '已回写审核报告', exact: true }).waitFor()
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出会议纪要', exact: true }).click()
    await (await download).saveAs(path.join(output, 'meeting.json'))
    await page.getByRole('button', { name: '返回项目报告', exact: true }).click()
    await page.locator('.report-addendum summary').first().waitFor()
    await page.locator('.report-addendum summary').first().click()
    const reportDownload = page.waitForEvent('download')
    await page.getByRole('link', { name: '导出报告', exact: true }).click()
    await (await reportDownload).saveAs(path.join(output, 'report.json'))
    if (!JSON.parse(fs.readFileSync(path.join(output, 'report.json'))).roundtable_addenda.length) throw Error('Roundtable not included in report')
    await page.getByRole('button', { name: '圆桌会议', exact: true }).click()
    if (await page.getByRole('button', { name: '发起圆桌会议', exact: true }).count()) throw Error('Global meeting nav creates empty meeting')
    await page.locator('.record-row').first().click()
    await page.getByRole('button', { name: '已回写审核报告', exact: true }).waitFor()
    await page.getByRole('button', { name: '出海营销项目', exact: true }).click()
    await page.getByRole('button', { name: '＋ 创建项目', exact: true }).click()
    await dialog.getByRole('radio', { name: '广告文案', exact: true }).check()
    await dialog.getByRole('textbox', { name: '广告文案', exact: true }).fill('Product copy.')
    await page.setViewportSize({ width: 390, height: 844 })
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Material dialog overflows')
    await page.screenshot({ path: path.join(output, 'material-dialog-mobile.png'), fullPage: true })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    for (const version of ['v1', 'v2']) {
      await page.evaluate(() => { localStorage.removeItem('marketing-court-session-v1'); localStorage.removeItem('marketing-court-preserved-v1') })
      await page.goto(`${app}/?ui=${version}`)
      await page.getByRole('button', { name: /打开预设案例/ }).waitFor()
    }
    if (errors.length) throw Error(errors.join('\n'))
    console.log('Workspace browser passed: project context, persona creation, issue-linked launch, independent roundtable, four role turns, refresh, conclusion writeback, report/meeting downloads, global history, mobile layout, v1/v2 preserved.')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })


